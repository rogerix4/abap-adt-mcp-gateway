/**
 * Shared engine types.
 *
 * The tool contract itself lives in `tools/catalog.json` and is frozen: names,
 * descriptions and input schemas are fixed, and no change here may alter them.
 * This file only describes how the engine reasons about them.
 */

/** JSON Schema for a tool's arguments. MCP requires an object schema. */
export interface ToolInputSchema {
  readonly type: "object";
  /** The contract's own required list — enforced in `ToolRegistry.call`. */
  readonly required?: readonly string[];
  readonly [key: string]: unknown;
}

/** One entry of the frozen tool contract. */
export interface ToolDefinition {
  readonly name: string;
  readonly description: string;
  readonly inputSchema: ToolInputSchema;
}

/** High-level tools do their own lock/activate; low-level ones leave that to the caller. */
export type ToolLayer = "high" | "low";

/**
 * What a tool does to the system.
 * - `read`: no state change
 * - `write`: creates/updates/activates/deletes objects or data
 * - `execute`: runs something inside the system (reports, tests, traces, profiling)
 */
export type ToolEffect = "read" | "write" | "execute";

/** What a tool needs the caller (or the engine) to supply before it can work. */
export interface ToolRequirements {
  /** Needs a `lock_handle` produced by a matching `Lock*` call. */
  readonly lockHandle: boolean;
  /** Needs `session_id` / `session_state` from `GetSession`. */
  readonly session: boolean;
}

/** Derived metadata for one tool. Generated by `tools/scripts/gen-layer-map.mjs`. */
export interface ToolMeta {
  readonly name: string;
  readonly verb: string;
  readonly subject: string;
  /** Object family the tool belongs to, used for implementation-coverage reporting. */
  readonly family: string;
  readonly layer: ToolLayer;
  /** Whether a same-subject tool exists in the other layer. */
  readonly hasHighSibling: boolean;
  readonly requires: ToolRequirements;
  readonly effect: ToolEffect;
}

/** Contract + metadata, the unit the registry hands out. */
export interface ToolEntry {
  readonly definition: ToolDefinition;
  readonly meta: ToolMeta;
}
